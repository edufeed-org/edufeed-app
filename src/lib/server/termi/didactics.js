/** The one-page didactics sheet of the Termi `lesson` prompt (German). */
export const DIDACTICS_SHEET = `Didaktik-Blatt (für Phase 3 und 5):
Phasierung einer 45-Minuten-Stunde: Einstieg 5–10 Min. (Anknüpfen an Vorwissen, Problem, Bild, Geschichte), Erarbeitung 20–25 Min. (eigenständiges Arbeiten allein, zu zweit oder in Gruppen), Sicherung 10–15 Min. (Ergebnisse vorstellen, vergleichen, festhalten, kurz üben). Bei 90 Minuten: zwei Erarbeitungsschleifen mit Zwischensicherung.
Methoden (wann):
• Think-Pair-Share — wenn alle erst allein nachdenken und dann ihre Idee prüfen sollen.
• Stationen — wenn ein Thema mehrere Zugänge oder Übungsformen hat und Tempo verschieden sein darf.
• Lerntempoduett — wenn Lernende unterschiedlich schnell sind: wer fertig ist, tauscht sich mit dem nächsten Fertigen aus.
• Placemat — wenn eine Gruppe Einzelideen sammeln und sich auf ein Ergebnis einigen soll.
• Galeriegang — wenn Gruppenergebnisse vorgestellt und gegenseitig kommentiert werden sollen.
• Partnerkarten — wenn zu zweit Wissen abgefragt und gefestigt werden soll (Frage vorne, Lösung hinten).
• Lernspiel — wenn Gelerntes spielerisch wiederholt oder automatisiert werden soll.
• Forscherauftrag — wenn Lernende etwas selbst entdecken, ausprobieren oder messen sollen.
• Lernplakat — wenn ein Ergebnis sichtbar festgehalten und später wieder genutzt werden soll.
• Kurzpräsentation — wenn Einzelne oder Gruppen ein Ergebnis in 1–3 Minuten erklären sollen.
Differenzierung: Niveaustufen A/B/C (Basis, Standard, Erweiterung); Wahlaufgaben; Hilfekarten mit gestuften Tipps; Legematerial und Anschauungsmittel; Sprachhilfen (Wortspeicher, Satzanfänge, Bilder zu Fachwörtern); mehr Zeit oder weniger Aufgaben statt anderer Ziele.
Grundschule: handlungsorientiert (anfassen, legen, bauen, spielen); vom Enaktiven über das Ikonische zum Symbolischen (erst handeln, dann zeichnen, dann Zeichen und Zahlen); kurze Phasen von 10–15 Minuten mit Wechsel der Sozialform und Bewegung; klare Rituale für Anfang und Ende.`;
